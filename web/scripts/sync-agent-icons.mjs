#!/usr/bin/env node
/**
 * Vendors the agent brand marks the Connections section shows.
 *
 * Why a build step rather than importing an icon component:
 *
 * `@lobehub/icons` — the component package — peer-depends on `antd@^6` and
 * `@lobehub/ui@^5`, and runtime-depends on `antd-style` (emotion) plus a
 * *second major version* of `lucide-react`. Pulling a full component library
 * and a rival CSS-in-JS runtime into a static brochure site, to render ten
 * glyphs, is not a trade worth making. `@lobehub/icons-static-svg` is the same
 * artwork with no dependencies at all, so it stays a devDependency and only its
 * extracted path data ships.
 *
 * The monochrome variants are used deliberately, never the `-color` ones: spec
 * §3.1 forbids a second palette on the page, and a row of vendor colours would
 * turn an index of what plugs in into the logo wall §4.5 rules out. In ink, the
 * marks read as the same kind of index mark as the numbered receipts beside
 * them.
 *
 * Output is committed, like every other file in `content/generated/`, so a
 * build never depends on this having been run.
 *
 * Usage: node scripts/sync-agent-icons.mjs [--check]
 *   --check  verify the committed output matches the installed package
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const HERE = dirname(fileURLToPath(import.meta.url))
const WEB_ROOT = join(HERE, "..")
const ICON_DIR = join(WEB_ROOT, "node_modules/@lobehub/icons-static-svg/icons")
const OUT_FILE = join(WEB_ROOT, "content/generated/agent-icons.json")

/**
 * The marks to vendor, keyed by the id the website content uses.
 *
 * Only agents Cognia actually interoperates with — the external-agent presets
 * in `lib/ai/agent/external/presets.ts` and the session-import adapters in
 * `lib/session-import/adapters/`. An agent with no mark in the package renders
 * with the site's own generic icon rather than a stand-in from another brand.
 */
export const AGENT_ICONS = [
  { id: "claude-code", file: "claudecode.svg" },
  { id: "codex", file: "codex.svg" },
  { id: "gemini-cli", file: "geminicli.svg" },
  { id: "cursor", file: "cursor.svg" },
  { id: "copilot", file: "githubcopilot.svg" },
  { id: "qwen", file: "qwen.svg" },
  { id: "opencode", file: "opencode.svg" },
  { id: "kiro", file: "kiro.svg" },
]

/** Pull the drawable parts out of a one-or-two-path lobehub monochrome icon. */
export function parseIcon(svg) {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1]
  if (!viewBox) throw new Error("no viewBox")

  const title = /<title>([^<]*)<\/title>/.exec(svg)?.[1] ?? null

  const paths = []
  for (const match of svg.matchAll(/<path\b([^>]*)>/g)) {
    const attrs = match[1]
    const d = /\sd="([^"]+)"/.exec(attrs)?.[1]
    if (!d) continue
    const fillRule = /fill-rule="([^"]+)"/.exec(attrs)?.[1]
    const clipRule = /clip-rule="([^"]+)"/.exec(attrs)?.[1]
    paths.push({ d, ...(fillRule ? { fillRule } : {}), ...(clipRule ? { clipRule } : {}) })
  }
  if (paths.length === 0) throw new Error("no drawable path")

  // A gradient or mask would not survive being reduced to bare paths, and would
  // silently render as a solid blob rather than failing. Refuse instead.
  if (/<(linearGradient|radialGradient|mask|clipPath|image)\b/.test(svg)) {
    throw new Error("icon uses a construct this extractor cannot carry")
  }

  return { viewBox, title, paths }
}

export function buildManifest(read = (file) => readFileSync(join(ICON_DIR, file), "utf8")) {
  const icons = {}
  for (const { id, file } of AGENT_ICONS) {
    icons[id] = { source: file, ...parseIcon(read(file)) }
  }
  return {
    note: "Generated by scripts/sync-agent-icons.mjs from @lobehub/icons-static-svg (MIT). Do not edit by hand.",
    icons,
  }
}

function main() {
  if (!existsSync(ICON_DIR)) {
    console.error(`[agent-icons] @lobehub/icons-static-svg is not installed at ${ICON_DIR}`)
    process.exit(1)
  }

  const manifest = buildManifest()
  const next = `${JSON.stringify(manifest, null, 2)}\n`

  if (process.argv.includes("--check")) {
    const current = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8") : ""
    if (current !== next) {
      console.error(
        "[agent-icons] committed output is stale — run `node scripts/sync-agent-icons.mjs`"
      )
      process.exit(1)
    }
    console.log(`[agent-icons] up to date (${Object.keys(manifest.icons).length} marks)`)
    return
  }

  mkdirSync(dirname(OUT_FILE), { recursive: true })
  writeFileSync(OUT_FILE, next, "utf8")
  console.log(`[agent-icons] wrote ${Object.keys(manifest.icons).length} marks to ${OUT_FILE}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
