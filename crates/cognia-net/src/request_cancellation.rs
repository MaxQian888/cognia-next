//! Generation-aware cancellation for request ids reused across async calls.

use std::collections::HashMap;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Mutex;
use std::time::{Duration, Instant};

use tokio::sync::oneshot;

struct Entry {
    generation: u64,
    sender: oneshot::Sender<()>,
}

/// A request-id registry that prevents an older request's cleanup from
/// unregistering a newer request that reused the same id.
#[derive(Default)]
pub struct RequestCancellationRegistry {
    next_generation: AtomicU64,
    entries: Mutex<HashMap<String, Entry>>,
}

impl RequestCancellationRegistry {
    /// Register `request_id`, cancelling any previous owner of that id.
    pub fn register(&self, request_id: &str) -> (u64, oneshot::Receiver<()>) {
        let generation = self.next_generation.fetch_add(1, Ordering::Relaxed);
        let (sender, receiver) = oneshot::channel();
        let previous = self.entries.lock().ok().and_then(|mut entries| {
            entries
                .insert(request_id.to_string(), Entry { generation, sender })
                .map(|entry| entry.sender)
        });
        if let Some(previous) = previous {
            let _ = previous.send(());
        }
        (generation, receiver)
    }

    /// Cancel the current owner of `request_id`.
    pub fn cancel(&self, request_id: &str) -> bool {
        self.entries
            .lock()
            .ok()
            .and_then(|mut entries| entries.remove(request_id))
            .is_some_and(|entry| entry.sender.send(()).is_ok())
    }

    /// Remove a completed registration only if it is still the current owner.
    pub fn finish(&self, request_id: &str, generation: u64) {
        if let Ok(mut entries) = self.entries.lock() {
            if entries
                .get(request_id)
                .is_some_and(|entry| entry.generation == generation)
            {
                entries.remove(request_id);
            }
        }
    }
}

struct Admission {
    token: String,
    expires: Instant,
    sender: Option<oneshot::Sender<()>>,
    receiver: Option<oneshot::Receiver<()>>,
}

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum RequestAdmissionError {
    #[error("request_admission_invalid")]
    Invalid,
    #[error("request_admission_full")]
    Full,
    #[error("request_admission_stale")]
    Stale,
}

/// Explicit, bounded admission for a caller that waits for prepare before send.
/// Tokens are generated by the owning host. Unknown/expired claims fail closed;
/// forgetting a reservation therefore never turns a cancelled request into I/O.
pub struct RequestAdmissionRegistry {
    entries: Mutex<HashMap<String, Admission>>,
    capacity: usize,
    ttl: Duration,
}

impl Default for RequestAdmissionRegistry {
    fn default() -> Self {
        Self {
            entries: Mutex::new(HashMap::new()),
            capacity: 256,
            ttl: Duration::from_secs(30),
        }
    }
}

impl RequestAdmissionRegistry {
    pub fn prepare(&self, request_id: &str, token: &str) -> Result<(), RequestAdmissionError> {
        self.prepare_at(request_id, token, Instant::now())
    }

    fn prepare_at(
        &self,
        request_id: &str,
        token: &str,
        now: Instant,
    ) -> Result<(), RequestAdmissionError> {
        if request_id.is_empty() || request_id.len() > 128 || token.is_empty() || token.len() > 128
        {
            return Err(RequestAdmissionError::Invalid);
        }
        let mut entries = self
            .entries
            .lock()
            .map_err(|_| RequestAdmissionError::Stale)?;
        entries.retain(|_, entry| entry.receiver.is_none() || entry.expires > now);
        if !entries.contains_key(request_id) && entries.len() >= self.capacity {
            return Err(RequestAdmissionError::Full);
        }
        let (sender, receiver) = oneshot::channel();
        if let Some(previous) = entries.insert(
            request_id.to_string(),
            Admission {
                token: token.to_string(),
                expires: now + self.ttl,
                sender: Some(sender),
                receiver: Some(receiver),
            },
        ) {
            if let Some(sender) = previous.sender {
                let _ = sender.send(());
            }
        }
        Ok(())
    }

    pub fn claim(
        &self,
        request_id: &str,
        token: &str,
    ) -> Result<(RequestAdmissionGuard<'_>, oneshot::Receiver<()>), RequestAdmissionError> {
        self.claim_at(request_id, token, Instant::now())
    }

    fn claim_at(
        &self,
        request_id: &str,
        token: &str,
        now: Instant,
    ) -> Result<(RequestAdmissionGuard<'_>, oneshot::Receiver<()>), RequestAdmissionError> {
        let mut entries = self
            .entries
            .lock()
            .map_err(|_| RequestAdmissionError::Stale)?;
        entries.retain(|_, entry| entry.receiver.is_none() || entry.expires > now);
        let entry = entries
            .get_mut(request_id)
            .filter(|entry| entry.token == token)
            .ok_or(RequestAdmissionError::Stale)?;
        let receiver = entry.receiver.take().ok_or(RequestAdmissionError::Stale)?;
        Ok((
            RequestAdmissionGuard {
                registry: self,
                request_id: request_id.to_string(),
                token: token.to_string(),
            },
            receiver,
        ))
    }

    pub fn cancel(&self, request_id: &str, token: &str) -> bool {
        let removed = self.entries.lock().ok().and_then(|mut entries| {
            if entries
                .get(request_id)
                .is_some_and(|entry| entry.token == token)
            {
                entries.remove(request_id)
            } else {
                None
            }
        });
        if let Some(mut entry) = removed {
            if let Some(sender) = entry.sender.take() {
                let _ = sender.send(());
            }
            true
        } else {
            false
        }
    }

    fn finish(&self, request_id: &str, token: &str) {
        if let Ok(mut entries) = self.entries.lock() {
            if entries
                .get(request_id)
                .is_some_and(|entry| entry.token == token)
            {
                entries.remove(request_id);
            }
        }
    }
}

/// Releases the exact admission even if validation fails or its future is dropped.
pub struct RequestAdmissionGuard<'a> {
    registry: &'a RequestAdmissionRegistry,
    request_id: String,
    token: String,
}

impl Drop for RequestAdmissionGuard<'_> {
    fn drop(&mut self) {
        self.registry.finish(&self.request_id, &self.token);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn prepared_cancel_reaches_a_later_claim_and_never_polls_work() {
        let registry = RequestAdmissionRegistry::default();
        registry.prepare("id", "generation-a").unwrap();
        assert!(registry.cancel("id", "generation-a"));
        assert!(!registry.cancel("id", "generation-a"));
        assert!(matches!(
            registry.claim("id", "generation-a"),
            Err(RequestAdmissionError::Stale)
        ));
        registry.prepare("id", "generation-b").unwrap();
        let (_guard, mut cancelled) = registry.claim("id", "generation-b").unwrap();
        assert!(registry.cancel("id", "generation-b"));
        tokio::select! {
            biased;
            _ = &mut cancelled => {},
            _ = async { panic!("cancelled work was polled") } => {},
        }
    }

    #[tokio::test]
    async fn stale_cancel_cleanup_and_duplicate_claim_cannot_affect_a_replacement() {
        let registry = RequestAdmissionRegistry::default();
        registry.prepare("same", "old").unwrap();
        let (old_guard, old_cancelled) = registry.claim("same", "old").unwrap();
        registry.prepare("same", "new").unwrap();
        assert!(old_cancelled.await.is_ok());
        let (new_guard, mut new_cancelled) = registry.claim("same", "new").unwrap();
        assert!(matches!(
            registry.claim("same", "new"),
            Err(RequestAdmissionError::Stale)
        ));
        drop(old_guard);
        assert!(!registry.cancel("same", "old"));
        assert!(matches!(
            new_cancelled.try_recv(),
            Err(oneshot::error::TryRecvError::Empty)
        ));
        assert!(registry.cancel("same", "new"));
        assert!(new_cancelled.await.is_ok());
        drop(new_guard);
        assert!(!registry.cancel("same", "new"));
        registry.prepare("same", "third").unwrap();
        let (_guard, mut third) = registry.claim("same", "third").unwrap();
        assert!(!registry.cancel("same", "new"));
        assert!(matches!(
            third.try_recv(),
            Err(oneshot::error::TryRecvError::Empty)
        ));
    }

    #[test]
    fn bounded_unclaimed_admissions_expire_into_rejection_not_network_permission() {
        let registry = RequestAdmissionRegistry {
            capacity: 2,
            ttl: Duration::from_secs(1),
            ..Default::default()
        };
        let now = Instant::now();
        registry.prepare_at("a", "a", now).unwrap();
        registry.prepare_at("b", "b", now).unwrap();
        assert_eq!(
            registry.prepare_at("c", "c", now),
            Err(RequestAdmissionError::Full)
        );
        assert!(!registry.cancel("unknown", "unknown"));
        assert_eq!(registry.entries.lock().unwrap().len(), 2);
        let later = now + Duration::from_secs(2);
        registry.prepare_at("c", "c", later).unwrap();
        assert!(matches!(
            registry.claim_at("a", "a", later),
            Err(RequestAdmissionError::Stale)
        ));
        assert!(matches!(
            registry.claim_at("c", "wrong", later),
            Err(RequestAdmissionError::Stale)
        ));
        let (guard, _receiver) = registry.claim_at("c", "c", later).unwrap();
        registry
            .prepare_at("d", "d", later + Duration::from_secs(2))
            .unwrap();
        assert!(
            registry.cancel("c", "c"),
            "active operations survive reservation expiry"
        );
        drop(guard);
        assert_eq!(registry.entries.lock().unwrap().len(), 1);
        assert_eq!(
            registry.prepare("", "token"),
            Err(RequestAdmissionError::Invalid)
        );
        assert_eq!(
            registry.prepare(&"x".repeat(129), "token"),
            Err(RequestAdmissionError::Invalid)
        );
    }

    #[tokio::test]
    async fn stale_cleanup_does_not_unregister_replacement() {
        let registry = RequestCancellationRegistry::default();
        let (first_generation, first_receiver) = registry.register("same-id");
        let (_second_generation, second_receiver) = registry.register("same-id");

        assert!(first_receiver.await.is_ok());
        registry.finish("same-id", first_generation);

        assert!(registry.cancel("same-id"));
        assert!(second_receiver.await.is_ok());
    }
}
