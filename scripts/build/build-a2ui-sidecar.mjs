#!/usr/bin/env node
// External MCP clients may still use Node 18; ship one dependency-free ESM file.
import { existsSync, statSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { build } from "esbuild"
import { newestMtimeMs } from "./lib/newest-mtime.mjs"

const root = join(dirname(fileURLToPath(import.meta.url)), "../..")
const outfile = join(root, "sidecar/a2ui-mcp.mjs")
const newest = Math.max(
  newestMtimeMs(join(root, "sidecar/src"), { exts: [".ts"] }),
  statSync(fileURLToPath(import.meta.url)).mtimeMs,
  statSync(join(root, "sidecar/package.json")).mtimeMs,
)
if (existsSync(outfile) && statSync(outfile).mtimeMs > newest) {
  console.log("[build-a2ui-sidecar] up to date; skipping")
} else {
  await build({
    entryPoints: [join(root, "sidecar/src/entry/a2ui-mcp.ts")],
    outfile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node18",
    tsconfig: join(root, "sidecar/tsconfig.json"),
    banner: { js: "// Generated by scripts/build/build-a2ui-sidecar.mjs. Do not edit." },
    logLevel: "info",
  })
  console.log("[build-a2ui-sidecar] ok -> sidecar/a2ui-mcp.mjs")
}
