import assert from "node:assert/strict"
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { test } from "node:test"

import {
  ICON_MODULES,
  ICON_SOURCE_DIR,
  REPO_ROOT,
  buildSignInIcons,
  encodeIcon,
  renderIconModule,
} from "./build-sign-in-icons.mjs"

test("every mapped icon exists in the spot icon set", () => {
  for (const target of ICON_MODULES) {
    for (const name of Object.values(target.icons)) {
      assert.ok(existsSync(path.join(REPO_ROOT, ICON_SOURCE_DIR, `${name}.png`)), name)
    }
  }
})

test("renders a typed module keyed by outcome", () => {
  const source = renderIconModule(
    { type: "T", exportName: "X", icons: { done: "terminal", failed: "diagnostics" } },
    { done: "data:image/webp;base64,AA", failed: "data:image/webp;base64,BB" }
  )
  assert.match(source, /^\/\/ Generated by scripts\/build\/build-sign-in-icons\.mjs/)
  assert.match(source, /export type T = "done" \| "failed"/)
  assert.match(source, /export const X_SOURCE: Record<T, string> = \{"done":"terminal"/)
  assert.match(source, /"failed": "data:image\/webp;base64,BB",/)
})

test("asks cwebp for a downscaled WebP and returns it as a data URI", () => {
  let args
  const uri = encodeIcon("/in.png", {
    pixels: 64,
    run: (command, argv) => {
      assert.equal(command, "cwebp")
      args = argv
      writeFileSync(argv[argv.indexOf("-o") + 1], Buffer.from("RIFFxxxxWEBP"))
    },
  })
  assert.deepEqual(args.slice(args.indexOf("-resize"), args.indexOf("-resize") + 3), [
    "-resize",
    "64",
    "64",
  ])
  assert.equal(uri, `data:image/webp;base64,${Buffer.from("RIFFxxxxWEBP").toString("base64")}`)
})

test("writes each module and refuses a missing icon", () => {
  const root = mkdtempSync(path.join(tmpdir(), "sign-in-icons-"))
  try {
    mkdirSync(path.join(root, ICON_SOURCE_DIR), { recursive: true })
    for (const target of ICON_MODULES) {
      mkdirSync(path.dirname(path.join(root, target.file)), { recursive: true })
      for (const name of Object.values(target.icons)) {
        writeFileSync(path.join(root, ICON_SOURCE_DIR, `${name}.png`), "")
      }
    }
    const written = buildSignInIcons({ root, encode: (source) => `data:${path.basename(source)}` })
    assert.equal(written.length, ICON_MODULES.length)
    assert.match(readFileSync(written[1], "utf8"), /"done": "data:terminal\.png"/)

    rmSync(path.join(root, ICON_SOURCE_DIR, "terminal.png"))
    assert.throws(() => buildSignInIcons({ root, encode: () => "" }), /no spot icon/)
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})
