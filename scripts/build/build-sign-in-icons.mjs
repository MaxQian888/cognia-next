#!/usr/bin/env node
/**
 * Inline copies of Cognia's chibi spot icons (public/icons/cognia-mobile-spots)
 * for the sign-in pages that cannot load them from the app:
 *
 * - the identity Worker's hosted pages (id.cognia.cn): its CSP allows images
 *   from `data:` only, and serving files would widen its route allowlist;
 * - the CLI's loopback callback page, which has nothing to serve them from.
 *
 * Each icon is downscaled to 288 px (twice the ~144 px it is drawn at) and
 * re-encoded as WebP, ~25 KB instead of the 512 px original's ~400 KB, then
 * written into a generated TypeScript module as a data URI. The app's own
 * `/logto/callback` page uses the originals through `MobileSpotIcon`.
 *
 * Needs `cwebp` (libwebp). Rerun after changing a mapping or an icon:
 *
 *   node scripts/build/build-sign-in-icons.mjs
 */

import { execFileSync } from "node:child_process"
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
export const ICON_SOURCE_DIR = "public/icons/cognia-mobile-spots/png"
export const ICON_PIXELS = 288

/** Which spot icon stands for each page outcome, per generated module. */
export const ICON_MODULES = [
  {
    file: "services/identity-server/src/pages/page-icons.ts",
    type: "PageIcon",
    exportName: "PAGE_ICONS",
    icons: {
      // The sign-in page: a Cognia account.
      welcome: "cloud-account",
      // Going straight to a provider.
      waiting: "network",
      // Signed in and handed back to the app.
      done: "workspace-trust",
      failed: "diagnostics",
      farewell: "profile",
      consent: "security",
    },
  },
  {
    file: "cli/src/mcp/callback-icons.ts",
    type: "CallbackIcon",
    exportName: "CALLBACK_ICONS",
    icons: {
      // Authorized: back to the terminal.
      done: "terminal",
      failed: "diagnostics",
    },
  },
]

/** The generated module's source. `uris` maps each key to its data URI. */
export function renderIconModule({ type, exportName, icons }, uris) {
  const keys = Object.keys(icons)
  const lines = [
    "// Generated by scripts/build/build-sign-in-icons.mjs. Do not edit; rerun it.",
    "// Downscaled copies of public/icons/cognia-mobile-spots, as WebP data URIs.",
    "",
    `export type ${type} = ${keys.map((key) => JSON.stringify(key)).join(" | ")}`,
    "",
    `/** The spot icon each key was made from. */`,
    `export const ${exportName}_SOURCE: Record<${type}, string> = ${JSON.stringify(icons)}`,
    "",
    `export const ${exportName}: Record<${type}, string> = {`,
    ...keys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(uris[key])},`),
    "}",
    "",
  ]
  return lines.join("\n")
}

/** Encode one source PNG with cwebp and return its data URI. */
export function encodeIcon(source, { run = execFileSync, pixels = ICON_PIXELS } = {}) {
  const dir = mkdtempSync(path.join(tmpdir(), "sign-in-icon-"))
  const out = path.join(dir, "icon.webp")
  try {
    run("cwebp", [
      "-quiet",
      "-q",
      "88",
      "-alpha_q",
      "90",
      "-m",
      "6",
      "-resize",
      String(pixels),
      String(pixels),
      source,
      "-o",
      out,
    ])
    return `data:image/webp;base64,${readFileSync(out).toString("base64")}`
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

export function buildSignInIcons({ root = REPO_ROOT, encode = encodeIcon } = {}) {
  const written = []
  for (const target of ICON_MODULES) {
    const uris = {}
    for (const [key, name] of Object.entries(target.icons)) {
      const source = path.join(root, ICON_SOURCE_DIR, `${name}.png`)
      if (!existsSync(source)) throw new Error(`build-sign-in-icons: no spot icon ${source}`)
      uris[key] = encode(source)
    }
    const file = path.join(root, target.file)
    writeFileSync(file, renderIconModule(target, uris))
    written.push(file)
  }
  return written
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const file of buildSignInIcons()) console.log(`wrote ${path.relative(REPO_ROOT, file)}`)
}
