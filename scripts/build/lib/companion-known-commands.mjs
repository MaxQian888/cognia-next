/**
 * The Rust command table (ADR-0175 B2).
 *
 * `protocol/companion-commands.json` is the contract. The host used to parse
 * that JSON at runtime AND keep a second, hand-typed `KNOWN_COMMANDS` array in
 * `rpc.rs` that had to be edited in lockstep. This module renders the contract
 * into one generated Rust table so the host compiles against the contract
 * instead of re-reading it, and the allowlist stops being typed twice.
 *
 * What is remote-executable is a fact of the contract, not of a Rust array: a
 * command whose `target` is not `client` has a dispatch arm and is reachable
 * over `/internal/_rpc` (and, by its transports, `/api/_rpc`).
 */

export const KNOWN_COMMANDS_RUST_PATH = "src-tauri/src/companion_api/generated/known_commands.rs"

const TARGET = { client: "Client", execution: "Execution", "host-admin": "HostAdmin", service: "Service" }
const OPERATION = { read: "Read", write: "Write", "side-effect": "SideEffect" }
const RISK = { low: "Low", high: "High", critical: "Critical" }
const APPROVAL = { none: "None", interactive: "Interactive", "signed-policy": "SignedPolicy" }
const IDEMPOTENCY = { structural: "Structural", required: "Required", forbidden: "Forbidden" }
const TRANSPORT = { http: "Http", websocket: "Websocket", webrtc: "Webrtc", internal: "Internal" }
const PAGINATION = { none: "None", "page-token": "PageToken", "byte-range": "ByteRange" }

/** The names the dispatcher answers: every descriptor whose target is not `client`. */
export function remoteCommandNames(manifest) {
  return new Set(
    manifest.commands.filter((command) => command.target !== "client").map((command) => command.name)
  )
}

function variant(table, value, field, name) {
  const mapped = table[value]
  if (mapped === undefined) {
    throw new Error(`command ${name}: unknown ${field} ${JSON.stringify(value)}`)
  }
  return mapped
}

function rustString(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`
}

function renderRow(command) {
  const transports = command.transports
    .map((transport) => `CommandTransport::${variant(TRANSPORT, transport, "transport", command.name)}`)
    .join(", ")
  return (
    `    WireCommand { ` +
    `name: ${rustString(command.name)}, ` +
    `arm: ${rustString(command.arm)}, ` +
    `resource: ${rustString(command.resource)}, ` +
    `verb: ${rustString(command.verb)}, ` +
    `target: CommandTarget::${variant(TARGET, command.target, "target", command.name)}, ` +
    `operation: CommandOperation::${variant(OPERATION, command.operation, "operation", command.name)}, ` +
    `capability: ${rustString(command.capability)}, ` +
    `risk: CommandRisk::${variant(RISK, command.risk, "risk", command.name)}, ` +
    `approval: CommandApproval::${variant(APPROVAL, command.approval, "approval", command.name)}, ` +
    `idempotency: CommandIdempotency::${variant(IDEMPOTENCY, command.idempotency, "idempotency", command.name)}, ` +
    `transports: &[${transports}], ` +
    `input_schema: ${rustString(command.inputSchema)}, ` +
    `output_schema: ${rustString(command.outputSchema)}, ` +
    `pagination: CommandPagination::${variant(PAGINATION, command.pagination, "pagination", command.name)}, ` +
    `long_running: ${command.longRunning ? "true" : "false"} },`
  )
}

/**
 * Render `known_commands.rs`.
 *
 * @param {{ manifest: { contractVersion: number, commands: object[] }, renames: { renames: Record<string, { to: string }> }, catalogHash: string }} input
 * @returns {string}
 */
export function renderKnownCommandsRust({ manifest, renames, catalogHash }) {
  if (!Number.isInteger(manifest.contractVersion)) {
    throw new Error("manifest.contractVersion must be an integer")
  }
  if (typeof catalogHash !== "string" || !/^[0-9a-f]{64}$/.test(catalogHash)) {
    throw new Error("catalogHash must be a sha256 hex digest")
  }
  const seen = new Set()
  for (const command of manifest.commands) {
    if (seen.has(command.name)) throw new Error(`duplicate command descriptor: ${command.name}`)
    seen.add(command.name)
  }
  const renameRows = Object.entries(renames.renames ?? {})
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([from, entry]) => `    (${rustString(from)}, ${rustString(entry.to)}),`)
  return [
    "//! Generated by scripts/build/gen-companion-api.mjs from",
    "//! protocol/companion-commands.json and protocol/companion-command-renames.json.",
    "//! Do not edit.",
    "//!",
    "//! ADR-0175: the command contract this host was compiled against.",
    "//! `command_manifest` reads this table instead of parsing JSON at runtime, and",
    "//! a `#[cfg(test)]` check there holds it row for row against the protocol",
    "//! file it was rendered from. `RENAMED_COMMANDS` answers an old wire name",
    "//! with 410 once the rename cut removes it from `WIRE_COMMANDS`.",
    "",
    "// Mounted by `command_manifest.rs` as `#[path = \"generated/known_commands.rs\"] pub mod known_commands;`,",
    "// so the enums and the row type are one level up.",
    "use super::{",
    "    CommandApproval, CommandIdempotency, CommandOperation, CommandPagination, CommandRisk,",
    "    CommandTarget, CommandTransport, WireCommand,",
    "};",
    "",
    "/// One version for the whole command contract.",
    `pub const CONTRACT_VERSION: u32 = ${manifest.contractVersion};`,
    "",
    "/// The sha256 of the Headless command catalog rendered from this contract.",
    `pub const CATALOG_HASH: &str = ${rustString(catalogHash)};`,
    "",
    "/// Every command in the contract, in contract order.",
    "#[rustfmt::skip]",
    "pub static WIRE_COMMANDS: &[WireCommand] = &[",
    ...manifest.commands.map(renderRow),
    "];",
    "",
    "/// Old wire name to its replacement, sorted by old name.",
    "#[rustfmt::skip]",
    "pub static RENAMED_COMMANDS: &[(&str, &str)] = &[",
    ...renameRows,
    "];",
    "",
  ].join("\n")
}
