import assert from "node:assert/strict"
import { mkdtemp, mkdir, readFile, readdir, rename, rm, symlink, writeFile } from "node:fs/promises"
import os from "node:os"
import path from "node:path"
import test from "node:test"
import JSZip from "jszip"
import { devShellCache, installedDevShellMatches } from "./android-dev-shell.mjs"

async function fixture(t) {
  const root = await mkdtemp(path.join(os.tmpdir(), "cognia-dev-cache-"))
  t.after(() => rm(root, { recursive: true, force: true }))
  const put = async (name, value) => {
    const file = path.join(root, name)
    await mkdir(path.dirname(file), { recursive: true })
    await writeFile(file, value)
  }
  const env = {
    COGNIA_MOBILE_DEV_URL: "http://localhost:3002",
    JAVA_HOME: path.join(root, "jdk"),
    GRADLE_USER_HOME: path.join(root, "gradle-user"),
  }
  const config = {
    appId: "com.cognia.mobile",
    server: { url: env.COGNIA_MOBILE_DEV_URL, cleartext: true },
    android: { webContentsDebuggingEnabled: true },
  }
  await put(
    "mobile/package.json",
    JSON.stringify({ dependencies: { "local-plugin": "workspace:*" } })
  )
  await put("mobile/node_modules/local-plugin/android/src/Plugin.java", "native plugin")
  await put("mobile/android/app/src/main/java/MainActivity.java", "native")
  await put("mobile/android/app/src/main/assets/capacitor.config.json", JSON.stringify(config))
  const writeApk = async (override = config) => {
    const zip = new JSZip()
    zip.file("assets/capacitor.config.json", JSON.stringify(override))
    zip.file("assets/public/index.html", "<!-- Generated by Cognia Android dev workflow. -->hello")
    await put(
      "mobile/android/app/build/outputs/apk/debug/app-debug.apk",
      await zip.generateAsync({ type: "nodebuffer" })
    )
  }
  await writeApk()
  return {
    root,
    put,
    env,
    config,
    writeApk,
    cache: devShellCache(root, env, { javaVersion: "javac 21" }),
  }
}

test("sealed APK survives offline outputs and JS/CSS edits while verifying its own bytes", async (t) => {
  const { root, cache, put } = await fixture(t)
  const inputs = await cache.fingerprint()
  assert.equal(await cache.find(inputs), null)
  const record = await cache.save(inputs, await cache.generated())
  assert.deepEqual(await cache.find(inputs), record)
  await put("app/page.tsx", "updated UI")
  await put("app/globals.css", "updated CSS")
  assert.equal(await cache.fingerprint(), inputs)
  await put("mobile/android/app/build/reports/random", "new build report")
  assert.equal(await cache.fingerprint(), inputs)
  const serialized = await readFile(
    path.join(root, ".cache/mobile-dev-shell/manifest.json"),
    "utf8"
  )
  assert.equal(serialized.includes("localhost"), false)
  assert.equal(serialized.includes("javac"), false)
  await put("mobile/android/app/src/main/assets/capacitor.config.json", "offline config")
  await put("mobile/android/capacitor.settings.gradle", "offline sync output")
  await put("mobile/android/app/build/outputs/apk/debug/app-debug.apk", "offline APK")
  assert.deepEqual(await cache.find(inputs), record)
  assert.equal(await cache.fingerprint(), inputs)
  assert.notEqual(record.apk, cache.sourceApk)
  await rm(record.apk)
  assert.equal(await cache.find(inputs), null)
})

test("native source, plugin bytes, config, lockfile, toolchain, and port invalidate reuse", async (t) => {
  const { root, cache, env, put } = await fixture(t)
  let prior = await cache.fingerprint()
  for (const file of [
    "mobile/android/app/src/main/java/MainActivity.java",
    "mobile/node_modules/local-plugin/android/src/Plugin.java",
    "mobile/capacitor.config.ts",
    "pnpm-lock.yaml",
    "jdk/release",
    "gradle-user/gradle.properties",
  ]) {
    await put(file, "changed")
    const next = await cache.fingerprint()
    assert.notEqual(next, prior, file)
    prior = next
  }
  assert.notEqual(
    await devShellCache(
      root,
      { ...env, COGNIA_MOBILE_DEV_URL: "http://localhost:4000" },
      { javaVersion: "javac 21" }
    ).fingerprint(),
    prior
  )
  assert.notEqual(
    await devShellCache(root, env, { javaVersion: "javac 21.1" }).fingerprint(),
    prior
  )
})

