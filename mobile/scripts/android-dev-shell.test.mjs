test("default, configured, and legacy debug signing key changes invalidate reuse without exposing bytes", async (t) => {
  const { root, env, put } = await fixture(t)
  t.mock.method(os, "homedir", () => path.join(root, "user"))
  const signingEnv = {
    ...env,
    ANDROID_USER_HOME: path.join(root, "android-user"),
    ANDROID_PREFS_ROOT: path.join(root, "prefs-user"),
    ANDROID_SDK_HOME: path.join(root, "legacy-user"),
  }
  const cache = devShellCache(root, signingEnv, { javaVersion: "javac 21" })
  for (const file of [
    "user/.android/debug.keystore",
    "android-user/debug.keystore",
    "prefs-user/.android/debug.keystore",
    "legacy-user/.android/debug.keystore",
  ]) {
    const missing = await cache.fingerprint()
    await put(file, "synthetic-private-key-one")
    const initial = await cache.fingerprint()
    assert.notEqual(initial, missing, `${file}: created`)
    await cache.save(initial, await cache.generated())
    await put(file, "synthetic-private-key-two")
    const changed = await cache.fingerprint()
    assert.notEqual(changed, initial, `${file}: replaced`)
    assert.equal(await cache.find(changed), null)
    await rm(path.join(root, file))
    assert.equal(await cache.fingerprint(), missing, `${file}: removed`)
  }
  assert.equal(
    (await readFile(path.join(root, ".cache/mobile-dev-shell/manifest.json"), "utf8")).includes(
      "synthetic-private-key"
    ),
    false
  )
})

test("signing initialization detects only the selected key and leaves creation to Gradle", async (t) => {
  const { root, env, put } = await fixture(t)
  t.mock.method(os, "homedir", () => path.join(root, "user"))
  const base = devShellCache(root, env, { javaVersion: "javac 21" })
  assert.equal(await base.needsSigningKey(), true)
  await put("user/.android/debug.keystore", "default signer")
  assert.equal(await base.needsSigningKey(), false)
  for (const [variable, relative] of [
    ["ANDROID_USER_HOME", "direct"],
    ["ANDROID_PREFS_ROOT", "prefs"],
    ["ANDROID_SDK_HOME", "legacy"],
  ]) {
    const directory = path.join(root, relative)
    const cache = devShellCache(
      root,
      { ...env, [variable]: directory },
      { javaVersion: "javac 21" }
    )
    if (variable !== "ANDROID_USER_HOME") {
      assert.equal(await cache.needsSigningKey(), false, "missing legacy parent falls back")
      await mkdir(directory)
    }
    assert.equal(
      await cache.needsSigningKey(),
      true,
      "default signer cannot mask selected missing key"
    )
    const key = `${relative}/${variable === "ANDROID_USER_HOME" ? "" : ".android/"}debug.keystore`
    await put(key, "configured signer")
    assert.equal(await cache.needsSigningKey(), false)
    await rm(path.join(root, key))
    assert.equal(await cache.needsSigningKey(), true)
  }
})

test("cache refuses mixed source/generated builds and offline APKs", async (t) => {
  const { cache, put, config, writeApk } = await fixture(t)
  const before = await cache.fingerprint()
  const outputs = await cache.generated()
  await put("mobile/android/app/src/main/java/MainActivity.java", "concurrent edit")
  await assert.rejects(cache.save(before, outputs), /mixed-source/)
  const current = await cache.fingerprint()
  await put("mobile/android/app/src/main/assets/extra.txt", "concurrent generated edit")
  await assert.rejects(cache.save(current, outputs), /mixed-source/)
  await writeApk({ ...config, server: {} })
  await assert.rejects(cache.save(current, await cache.generated()), /expected live-reload shell/)
  assert.equal(await cache.find(current), null)
})

