test("old cache versions, wrong inputs, malformed hashes, and linked cached APKs refuse reuse", async (t) => {
  const { root, cache } = await fixture(t)
  const inputs = await cache.fingerprint()
  const cached = await cache.save(inputs, await cache.generated())
  const manifest = path.join(root, ".cache/mobile-dev-shell/manifest.json")
  const original = await readFile(manifest, "utf8")
  for (const change of [
    { version: 1 },
    { generated: "invalid" },
    { apkHash: "../../outside" },
    { inputs: "stale" },
  ]) {
    await writeFile(manifest, JSON.stringify({ ...JSON.parse(original), ...change }))
    assert.equal(await cache.find(inputs), null)
  }
  await writeFile(manifest, original)
  await rm(cached.apk)
  await symlink(cache.sourceApk, cached.apk)
  assert.equal(await cache.find(inputs), null)
})

test("publication keeps one APK and cleans owned orphan files without touching other files", async (t) => {
  const { root, cache, put, writeApk, config } = await fixture(t)
  const inputs = await cache.fingerprint()
  const first = await cache.save(inputs, await cache.generated())
  await put(".cache/mobile-dev-shell/readme.txt", "user note")
  await put(`.cache/mobile-dev-shell/${"a".repeat(64)}.apk`, "orphan")
  await put(".cache/mobile-dev-shell/.publish-abcd.apk.tmp", "interrupted write")
  const changed = { ...config, appName: "new native config" }
  await put("mobile/android/app/src/main/assets/capacitor.config.json", JSON.stringify(changed))
  await writeApk(changed)
  const second = await cache.save(inputs, await cache.generated())
  assert.notEqual(first.apk, second.apk)
  assert.deepEqual(await cache.find(inputs), second)
  assert.deepEqual(
    (await readdir(path.join(root, ".cache/mobile-dev-shell"))).sort(),
    [path.basename(second.apk), "manifest.json", "readme.txt"].sort()
  )
})

test("failed staging writes or manifest publication preserve the previous verified APK", async (t) => {
  const { root, cache, env, put, writeApk, config } = await fixture(t)
  const inputs = await cache.fingerprint()
  const first = await cache.save(inputs, await cache.generated())
  const changed = { ...config, appName: "new native config" }
  await put("mobile/android/app/src/main/assets/capacitor.config.json", JSON.stringify(changed))
  await writeApk(changed)
  for (const failure of ["write", "publish"]) {
    const faulty = devShellCache(
      root,
      env,
      { javaVersion: "javac 21" },
      {
        writeFile: async (...args) => {
          if (failure === "write" && String(args[0]).endsWith(".json.tmp"))
            throw new Error("disk full")
          return writeFile(...args)
        },
        rename: async (from, to) => {
          if (failure === "publish" && to.endsWith("manifest.json"))
            throw new Error("publish failed")
          return rename(from, to)
        },
      }
    )
    await assert.rejects(faulty.save(inputs, await cache.generated()), /disk full|publish failed/)
    assert.deepEqual(await cache.find(inputs), first)
    assert.deepEqual(
      (await readdir(path.join(root, ".cache/mobile-dev-shell"))).sort(),
      [path.basename(first.apk), "manifest.json"].sort()
    )
  }
})

test("source or generated changes during staging cannot publish a verified cache", async (t) => {
  for (const source of [true, false]) {
    const { root, cache, env, put } = await fixture(t)
    const inputs = await cache.fingerprint()
    const outputs = await cache.generated()
    const faulty = devShellCache(
      root,
      env,
      { javaVersion: "javac 21" },
      {
        writeFile: async (...args) => {
          await writeFile(...args)
          if (String(args[0]).endsWith(".apk.tmp"))
            await put(
              source
                ? "mobile/android/app/src/main/java/MainActivity.java"
                : "mobile/android/app/src/main/assets/extra.txt",
              "concurrent edit"
            )
        },
      }
    )
    await assert.rejects(faulty.save(inputs, outputs), /before cache publication/)
    assert.equal(await cache.find(inputs), null)
    assert.deepEqual(await readdir(path.join(root, ".cache/mobile-dev-shell")), [])
  }
})

test("installed package must have exactly matching APK bytes; missing/unreadable/split/malicious paths fail closed", async () => {
  const hash = "a".repeat(64)
  const apk = "/data/app/~~id/com.cognia.mobile-id/base.apk"
  const invoke = async (listing, output) =>
    installedDevShellMatches(async (args) => {
      if (args.includes("path")) return listing
      if (output instanceof Error) throw output
      return output
    }, hash)
  assert.equal(await invoke(`package:${apk}`, `${hash}  ${apk}\n`), true)
  assert.equal(await invoke(`package:${apk}`, `${"b".repeat(64)}  ${apk}`), false)
  assert.equal(await invoke(`package:${apk}`, new Error("permission denied")), false)
  assert.equal(await invoke(`package:${apk}`, `${hash}  /different.apk`), false)
  for (const listing of [
    "",
    "package:/data/app/a;evil.apk",
    `package:${apk}\npackage:/data/app/split.apk`,
  ])
    assert.equal(await invoke(listing, `${hash}  ${apk}`), false)
  const calls = []
  assert.equal(
    await installedDevShellMatches(async (args) => {
      calls.push(args)
      if (args.includes("path")) return `package:${apk}`
      if (!args.includes("toybox")) throw new Error("command missing")
      return `${hash}  ${apk}`
    }, hash),
    true
  )
  assert.equal(calls.length, 3)
})
