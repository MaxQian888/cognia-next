/**
 * Status state machine. Order in this union is also the priority order used
 * by `lib/goal/exit-conditions.ts:evaluateExitConditions`.
 *
 *   active           → driving forward
 *   paused           → resumable; turn driver yields
 *   completed        → judge said done=true (terminal)
 *   stopped          → user `/goal stop|cancel|clear` (terminal)
 *   budget_limited   → tokensUsed >= maxTokens (terminal)
 *   turn_limited     → turnsUsed >= maxTurns (terminal)
 *   timed_out        → wall-clock exceeded timeoutMs (terminal)
 *   preempted        → user typed a non-slash message mid-loop (terminal)
 */
export type GoalStatus =
  | "active"
  | "paused"
  | "completed"
  | "stopped"
  | "budget_limited"
  | "turn_limited"
  | "timed_out"
  | "preempted"

/**
 * A single decomposed step of a goal's objective (ADR-0019 "Future Work" →
 * subgoal decomposition, landed). Generated by `lib/goal/subgoals.ts` from
 * the redacted `safeObjective` and stored as a JSON array on the `Goal` row
 * (non-indexed — Dexie persists it without a schema-version bump). `done`
 * is toggled manually from the Subgoals tab or auto-marked by the judge's
 * optional `completedSubgoals` verdict.
 */
export interface GoalSubgoal {
  /** UUIDv4, stable across re-renders and toggles. */
  id: string
  /** The step text (already redacted — derived from `safeObjective`). */
  text: string
  /** Whether the step has been completed. */
  done: boolean
  /** Ascending display/order index (0-based). */
  order: number
}

/** True when the status is terminal (cannot transition out). */
export function isTerminalGoalStatus(status: GoalStatus): boolean {
  return (
    status === "completed" ||
    status === "stopped" ||
    status === "budget_limited" ||
    status === "turn_limited" ||
    status === "timed_out" ||
    status === "preempted"
  )
}

/**
 * Quiet-hours window during which the goal loop defers its next
 * continuation. Identical shape to `ConversationOverrideRow.quietHours` so
 * `lib/connectors/outbound-runner.ts:isInQuietHours` / `msUntilQuietEnd`
 * consume it unchanged.
 */
export interface GoalQuietHours {
  /** Window start, "HH:mm" 24-hour. */
  from: string
  /** Window end, "HH:mm" 24-hour. Crosses midnight when `to < from`. */
  to: string
  /** IANA time zone id, e.g. "Asia/Shanghai". */
  tz: string
}

/** Per-goal knobs — defaults come from `AppSettings.goals` via `lib/goal/runtime.ts:resolveGoalConfig`. */
export interface GoalConfig {
  /** Hard cap on completed turns. Default 20 (Hermes default). Range 1..100. */
  maxTurns: number
  /** Hard cap on cumulative tokens (input + output). Default 200_000. */
  maxTokens: number
  /**
   * Consecutive judge JSON parse failures before the goal auto-pauses
   * (fail-OPEN: never wedge on judge flakiness). Default 3 (Hermes default).
   */
  maxJudgeFailures: number
  /** Wall-clock timeout in ms. Default 30 * 60_000 (30 min). */
  timeoutMs: number
  /**
   * User-supplied "or stop after N turns" condition appended to the system
   * prompt verbatim. Claude Code-style escape hatch when the model's own
   * judgment of "done" feels unreliable for the task.
   */
  inlineStopCondition?: string

  // ── Judge customization (ADR-0019 Phase 2) ──────────────────────────────
  /**
   * Judge model id (e.g. "claude-haiku-4-5"). Undefined → the chat hook
   * builds the judge client from the session's chat model.
   */
  judgeModel?: string
  /** Provider id paired with `judgeModel`. Undefined → session/app provider. */
  judgeProvider?: string
  /** Full replacement for `JUDGE_SYSTEM_PROMPT`. Empty/undefined → built-in. */
  judgePromptOverride?: string
  /** Judge sampling temperature. Undefined → 0 (judge wants determinism). */
  judgeTemperature?: number
  /** Hard cap on judge response tokens. Undefined → 200. */
  judgeMaxTokens?: number

  // ── Pacing / manual control (ADR-0019 Phase 2) ──────────────────────────
  /**
   * When true, the loop HOLDS the continuation — the user clicks "Continue"
   * on the status pill to advance one turn. See `gateContinuation`.
   */
  manualContinue?: boolean
  /** Minimum wall-clock ms between auto-continuations. Undefined → 0 (none). */
  continuationIntervalMs?: number
  /** Defer the next continuation while inside this window. */
  quietHours?: GoalQuietHours

  // ── Completion-promise gate + adaptive pacing ────────────────────────────
  /**
   * Anti false-completion gate (Ralph-style). When set, a judge `done=true`
   * verdict does NOT terminate the goal directly: the loop runs one
   * verification turn asking the model to emit the exact
   * `<promise>TEXT</promise>` token ONLY if the objective is unequivocally
   * satisfied (with an explicit no-lying instruction). Empty/undefined →
   * the judge verdict terminates the goal exactly as before.
   */
  completionPromise?: string
  /**
   * Consecutive failed verification turns before the gate is overridden —
   * the judge has re-affirmed done that many times, so the goal completes
   * with a `promise_denied(overridden)` audit event. Undefined → 3.
   */
  maxPromiseDenials?: number
  /**
   * Opt-in adaptive pacing: continuation messages instruct the model to
   * suggest the next delay (`<next-delay minutes=N reason="..."/>`). The
   * gate honors max(continuationIntervalMs, suggestion) — the model can only
   * SLOW the loop, never speed it below the configured interval. Bounded
   * 1–60 minutes.
   */
  adaptivePacing?: boolean
}

export interface Goal {
  /** UUIDv4. Globally unique; safe to use as a Dexie primary key. */
  id: string
  /** FK → ChatSession.id. Session-scoped: at most one row with status==="active" per sessionId. */
  sessionId: string
  /**
   * Snapshot of the character at goal creation time. UI only — used by the
   * Activity tab to render the right avatar even after the user switches
   * the session's character.
   */
  characterId?: string
  /**
   * User's original objective text, preserved verbatim for the UI to
   * display ("show me what I asked for"). NEVER concatenated into a prompt
   * directly — `safeObjective` is what reaches the LLM.
   */
  rawObjective: string
  /**
   * PII-redacted objective. Goes into `<objective>` XML tag in the system
   * prompt and into judge prompts. Built by `lib/goal/redact-objective.ts`.
   */
  safeObjective: string
  /**
   * Encrypted PII↔placeholder map (base64 ciphertext + nonce + tag).
   * Tauri: encrypted with the keyring-derived data key. Web: AES-GCM with a
   * key derived from `AppSettings.id` (best-effort; the web build flags this
   * as a degraded mode in the docs). Empty string when no PII was found.
   */
  redactionMapEnc: string
  status: GoalStatus
  /** Number of model turns completed against this goal so far. */
  turnsUsed: number
  /** Cumulative input + output tokens billed against this goal. */
  tokensUsed: number
  /**
   * Consecutive judge parse failures since the last successful judge call.
   * Resets to 0 on success. When ≥ `config.maxJudgeFailures` the
   * `judge_failed_too_many` exit fires.
   */
  judgeFailureCount: number
  config: GoalConfig
  /**
   * Race guard. Every status mutation rotates this string (UUIDv4). The turn
   * driver captures the generationId at evaluation start and refuses to
   * schedule the next continuation if it changed.
   */
  generationId: string
  createdAt: number
  updatedAt: number
  /** Set when status becomes terminal. Drives History sorting + reset countdown. */
  endedAt?: number
  /**
   * Decomposed checklist of the objective (subgoal decomposition). Absent
   * until the user generates it from the Subgoals tab. Stored inline as JSON
   * — no Dexie index, so adding it needs no schema migration.
   */
  subgoals?: GoalSubgoal[]
  /** Timestamp (ms) of the last `generateSubgoals` run. Drives "regenerate" UX. */
  subgoalsGeneratedAt?: number
  /**
   * True while the completion-promise verification turn is in flight: the
   * NEXT response is graded for the `<promise>` token instead of being
   * re-judged. Persisted (inline, no schema bump) so a reload
   * mid-verification resumes correctly.
   */
  awaitingPromise?: boolean
  /**
   * Consecutive failed verification turns. Persists across re-armed gates
   * (only a confirmed promise or an objective update resets it) so repeated
   * judge-done → denial cycles eventually override at `maxPromiseDenials`.
   */
  promiseDenialCount?: number
  /**
   * Epoch ms of the next scheduled auto-continuation — set when the pacing
   * gate defers, cleared on dispatch. Drives the status pill's
   * "next continuation at…" footnote. Inline, no schema bump.
   */
  nextContinuationAt?: number
  /** Why the continuation was deferred — i18n category for the pill footnote. */
  nextContinuationSource?: "interval" | "quiet_hours" | "model_suggested"
}

