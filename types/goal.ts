/**
 * Discriminator for `GoalEvent.payload` shape. Each kind has a payload
 * declared inline below; the union here drives `chatGoalEvents` index lookups
 * (filter by kind in the Activity tab).
 */
export type GoalEventKind =
  | "goal_created"
  | "objective_updated"
  | "turn_started"
  | "turn_completed"
  | "judge_evaluated"
  | "judge_parse_failed"
  | "exit_triggered"
  | "user_paused"
  | "user_resumed"
  | "user_stopped"
  | "config_updated"
  | "subgoals_generated"
  | "promise_requested"
  | "promise_confirmed"
  | "promise_denied"
  | "pacing_decided"

/**
 * Per-kind payloads. Keep these structurally typed (TypeScript discriminated
 * union via `kind`) — it lets the Activity tab render kind-specific cards
 * without runtime checks beyond the discriminator.
 */
export type GoalEventPayload =
  | { kind: "goal_created"; safeObjective: string; config: GoalConfig }
  | { kind: "objective_updated"; oldSafeObjective: string; newSafeObjective: string }
  | { kind: "turn_started"; turnNumber: number }
  | {
      kind: "turn_completed"
      turnNumber: number
      tokensDelta: number
      modelMessageId?: string
    }
  | {
      kind: "judge_evaluated"
      done: boolean
      reason: string
      judgeTokens: number
    }
  | { kind: "judge_parse_failed"; raw: string; failureCount: number }
  | { kind: "exit_triggered"; exit: ExitReason; reason: string }
  | { kind: "user_paused" }
  | { kind: "user_resumed" }
  | { kind: "user_stopped" }
  | { kind: "config_updated"; before: GoalConfig; after: GoalConfig }
  | { kind: "subgoals_generated"; count: number }
  | { kind: "promise_requested"; turnNumber: number }
  | { kind: "promise_confirmed"; turnNumber: number }
  | {
      kind: "promise_denied"
      turnNumber: number
      denialCount: number
      /** True when the denial cap was reached and the gate completed anyway. */
      overridden: boolean
    }
  | {
      kind: "pacing_decided"
      source: "interval" | "quiet_hours" | "model_suggested"
      untilMs: number
      /** The model-suggested delay (clamped, ms) when adaptive pacing fed the decision. */
      suggestedMs?: number
    }

export interface GoalEvent {
  /** UUIDv4 primary key. */
  id: string
  /** FK → Goal.id. Cascade-delete is performed at the CRUD layer (lib/db/goals.ts). */
  goalId: string
  kind: GoalEventKind
  ts: number
  payload: GoalEventPayload
}

