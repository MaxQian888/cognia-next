/**
 * @jest-environment jsdom
 * @jest-environment-options {"url":"https://www.youtube.com/watch?v=current"}
 */
import { isYouTubeWatchUrl, readYouTubeTranscript } from "./youtube-transcript"

type Track = { languageCode: string; baseUrl: string; kind?: string; isDefault?: boolean }
const track = (languageCode: string, kind?: string): Track => ({
  languageCode,
  kind,
  baseUrl: `https://www.youtube.com/api/timedtext?lang=${languageCode}`,
})
const pageWindow = window as Window & { ytInitialPlayerResponse?: unknown }
function response(tracks: Track[], extra: Record<string, unknown> = {}, id = "current") {
  return {
    videoDetails: { videoId: id },
    captions: { playerCaptionsTracklistRenderer: { captionTracks: tracks, ...extra } },
  }
}
const fetchMock = jest.fn()
const originalFetch = globalThis.fetch

describe("isYouTubeWatchUrl", () => {
  it.each([
    "https://www.youtube.com/watch?v=abc",
    "https://m.youtube.com/watch?v=abc",
    "https://music.youtube.com/watch?v=abc",
    "https://youtu.be/abc?t=2",
    "https://youtube.com/shorts/abc",
    "https://www.youtube.com/live/abc",
  ])("accepts %s", (url) => expect(isYouTubeWatchUrl(url)).toBe(true))
  it.each([
    "https://www.youtube.com/",
    "https://www.youtube.com/watch",
    "https://www.youtube.com/watch?v=",
    "https://youtube.com.evil.test/watch?v=abc",
    "https://youtu.be/",
    "https://youtu.be/a/b",
    "https://example.com/watch?v=abc",
    "javascript:alert(1)",
    "invalid",
  ])("rejects %s", (url) => expect(isYouTubeWatchUrl(url)).toBe(false))
})

describe("readYouTubeTranscript", () => {
  beforeEach(() => {
    window.history.replaceState({}, "", "/watch?v=current")
    document.body.innerHTML = '<div id="movie_player"></div>'
    pageWindow.ytInitialPlayerResponse = response([track("en")])
    fetchMock.mockReset().mockResolvedValue({
      ok: true,
      json: async () => ({ events: [{ tStartMs: 1250, segs: [{ utf8: "Hello" }] }] }),
    })
    globalThis.fetch = fetchMock
  })
  afterEach(() => {
    delete pageWindow.ytInitialPlayerResponse
    globalThis.fetch = originalFetch
  })

  it("merges json3 segments, ignores blank events and formats minutes and hours", async () => {
    fetchMock.mockResolvedValue({
      ok: true,
      json: async () => ({
        events: [
          { tStartMs: 62345, segs: [{ utf8: " Hello " }, { utf8: " world\nagain " }] },
          { tStartMs: 3602000, segs: [{ utf8: "An hour" }] },
          { segs: [{ utf8: "\n" }] },
          {},
          { segs: [{ utf8: 7 }] },
        ],
      }),
    })
    expect(await readYouTubeTranscript("en")).toEqual({
      status: "available",
      text: "[1:02] Hello world again\n[1:00:02] An hour",
      truncated: false,
      language: "en",
      autoGenerated: false,
    })
    expect(fetchMock).toHaveBeenCalledWith(
      "https://www.youtube.com/api/timedtext?lang=en&fmt=json3",
      { credentials: "same-origin" }
    )
  })

  it("prefers the player's current response over stale initial data", async () => {
    const player = document.querySelector("#movie_player") as Element & {
      getPlayerResponse: () => unknown
    }
    player.getPlayerResponse = () => response([track("fr")])
    pageWindow.ytInitialPlayerResponse = response([track("en")], {}, "previous")
    expect(await readYouTubeTranscript("fr")).toMatchObject({ status: "available", language: "fr" })
  })

  it("refuses stale video ids without fetching captions from the previous video", async () => {
    pageWindow.ytInitialPlayerResponse = response([track("en")], {}, "previous")
    expect(await readYouTubeTranscript("en")).toEqual({
      status: "unavailable",
      reason: "fetch_failed",
    })
    expect(fetchMock).not.toHaveBeenCalled()
  })

  it("falls back when the player throws or has a stale response", async () => {
    const player = document.querySelector("#movie_player") as Element & {
      getPlayerResponse: () => unknown
    }
    player.getPlayerResponse = () => {
      throw new Error("not ready")
    }
    expect(await readYouTubeTranscript("en")).toMatchObject({ status: "available" })
    player.getPlayerResponse = () => response([track("fr")], {}, "previous")
    expect(await readYouTubeTranscript("en")).toMatchObject({ status: "available", language: "en" })
  })

  it.each([
    {
      tracks: [track("en"), track("en-GB", "asr")],
      preferred: "en-GB",
      expected: "en-GB",
      extra: {},
    },
    { tracks: [track("fr"), track("en")], preferred: "en-US", expected: "en", extra: {} },
    { tracks: [track("fr"), track("en-GB")], preferred: "en-US", expected: "en-GB", extra: {} },
    {
      tracks: [track("en"), track("fr", "asr")],
      preferred: "ja",
      expected: "fr",
      extra: { audioTracks: [{ defaultCaptionTrackIndex: 1 }] },
    },
    {
      tracks: [track("en"), { ...track("fr", "asr"), isDefault: true }],
      preferred: "ja",
      expected: "fr",
      extra: {},
    },
    { tracks: [track("en", "asr"), track("fr")], preferred: "ja", expected: "fr", extra: {} },
    {
      tracks: [track("en", "asr"), track("fr", "asr")],
      preferred: "ja",
      expected: "en",
      extra: {},
    },
  ])(
    "selects $expected for $preferred using the required priority",
    async ({ tracks, preferred, expected, extra }) => {
      pageWindow.ytInitialPlayerResponse = response(tracks, extra)
      expect(await readYouTubeTranscript(preferred)).toMatchObject({
        status: "available",
        language: expected,
        autoGenerated: tracks.find((item) => item.languageCode === expected)!.kind === "asr",
      })
    }
  )

  it("returns not_a_video off watch pages and no_captions when tracks are absent", async () => {
    window.history.replaceState({}, "", "/results?search_query=hello")
    expect(await readYouTubeTranscript("en")).toEqual({
      status: "unavailable",
      reason: "not_a_video",
    })
    window.history.replaceState({}, "", "/watch?v=current")
    pageWindow.ytInitialPlayerResponse = { videoDetails: { videoId: "current" } }
    expect(await readYouTubeTranscript("en")).toEqual({
      status: "unavailable",
      reason: "no_captions",
    })
    expect(fetchMock).not.toHaveBeenCalled()
  })

  it.each(["network", "http", "empty", "json"])(
    "reports fetch_failed for %s failure",
    async (failure) => {
      if (failure === "network") fetchMock.mockRejectedValue(new Error("offline"))
      if (failure === "http") fetchMock.mockResolvedValue({ ok: false })
      if (failure === "empty")
        fetchMock.mockResolvedValue({ ok: true, json: async () => ({ events: [] }) })
      if (failure === "json")
        fetchMock.mockResolvedValue({
          ok: true,
          json: async () => {
            throw new Error("invalid JSON")
          },
        })
      expect(await readYouTubeTranscript("en")).toEqual({
        status: "unavailable",
        reason: "fetch_failed",
      })
    }
  )

  it("refuses a transcript if navigation completes during the fetch", async () => {
    fetchMock.mockImplementation(async () => {
      window.history.replaceState({}, "", "/watch?v=next")
      return { ok: true, json: async () => ({ events: [{ segs: [{ utf8: "Old video" }] }] }) }
    })
    expect(await readYouTubeTranscript("en")).toEqual({
      status: "unavailable",
      reason: "fetch_failed",
    })
  })

  it("still works after function serialization without module closures", async () => {
    const serialized = new Function(
      `return (${readYouTubeTranscript.toString()})`
    )() as typeof readYouTubeTranscript
    expect(await serialized("en")).toMatchObject({ status: "available", language: "en" })
  })
})
