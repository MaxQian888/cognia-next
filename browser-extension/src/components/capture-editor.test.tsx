/** @jest-environment jsdom */
import { fireEvent, render, screen } from "@testing-library/react"

import type { BrowserApi } from "@ext/src/lib/browser-api"
import type { CapturedPage } from "@ext/src/lib/panel-state"

import { CaptureEditor } from "./capture-editor"

const api = { message: (key: string) => key } as unknown as BrowserApi

const PAGE: CapturedPage = {
  tabId: 1,
  title: "Title",
  url: "https://a.test/",
  rawUrl: "https://a.test/",
  selection: { text: "plain", truncated: false, markdown: "**plain**" },
  readableText: null,
  capturedAt: 1,
  strippedQuery: false,
  metadata: { siteName: "A", byline: "Ann", publishedAt: "2026-10-01", lang: "en" },
  transcript: {
    status: "available",
    text: "[0:00] hi",
    truncated: true,
    language: "en",
    autoGenerated: true,
  },
  link: { url: "https://b.test/", text: "B" },
  image: { url: "https://c.test/i.png" },
}

describe("CaptureEditor", () => {
  it("edits the title and the mode's text", () => {
    const onChange = jest.fn()
    render(<CaptureEditor api={api} page={PAGE} mode="selection" onChange={onChange} />)
    expect(screen.getByTestId("capture-text-input")).toHaveValue("**plain**")
    fireEvent.change(screen.getByTestId("capture-title-input"), { target: { value: "New" } })
    expect(onChange).toHaveBeenLastCalledWith({ ...PAGE, title: "New" })
    fireEvent.change(screen.getByTestId("capture-text-input"), { target: { value: "cut" } })
    expect(onChange.mock.lastCall?.[0].selection).toEqual({
      text: "cut",
      truncated: false,
      markdown: "cut",
    })
  })

  it("shows what rides along: metadata, transcript, link and image", () => {
    render(<CaptureEditor api={api} page={PAGE} mode="metadata" onChange={jest.fn()} />)
    expect(screen.queryByTestId("capture-text-input")).toBeNull()
    expect(screen.getByTestId("capture-metadata")).toHaveTextContent("Ann")
    expect(screen.getByTestId("capture-transcript")).toHaveTextContent("transcriptAvailable")
    expect(screen.getByTestId("capture-transcript")).toHaveTextContent("transcriptAutoGenerated")
    expect(screen.getByTestId("capture-link")).toHaveTextContent("B — https://b.test/")
    expect(screen.getByTestId("capture-image")).toHaveTextContent("https://c.test/i.png")
  })

  it("states a missing transcript rather than hiding it", () => {
    render(
      <CaptureEditor
        api={api}
        page={{ ...PAGE, transcript: { status: "unavailable", reason: "no_captions" } }}
        mode="metadata"
        onChange={jest.fn()}
      />
    )
    expect(screen.getByTestId("capture-transcript")).toHaveTextContent("transcriptNoCaptions")
  })
})
